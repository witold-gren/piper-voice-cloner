"""Write piper_voice_cloner/editor/www/vendor/mdi.js: the Material Design Icons the editor uses.

The editor runs on a machine that may have no internet, so it carries the SVG paths of only the
icons named as "mdi:<name>" in its own files (www/*.js). Run after adding an icon:

    python dev/icons.py            (downloads @mdi/js once into .cache/mdi.js)
"""

from __future__ import annotations

import json
from pathlib import Path
import re
import sys
import urllib.request

REPO = Path(__file__).resolve().parents[1]
WWW = REPO / "piper_voice_cloner" / "editor" / "www"
TARGET = WWW / "vendor" / "mdi.js"
CACHE = REPO / ".cache" / "mdi.js"
MDI_URL = "https://cdn.jsdelivr.net/npm/@mdi/js@7.4.47/mdi.js"
USED = re.compile(r"mdi:([a-z0-9-]+)")
EXPORT = re.compile(r'export var (mdi\w+) = "([^"]+)"')


def used_icons(www: Path = WWW) -> set[str]:
    names: set[str] = set()
    for path in www.glob("*.js"):
        names.update(USED.findall(path.read_text(encoding="utf-8")))
    return names


def camel(name: str) -> str:
    return "mdi" + "".join(part.capitalize() for part in name.split("-"))


def main() -> int:
    if not CACHE.is_file():
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(MDI_URL, CACHE)
    paths = dict(EXPORT.findall(CACHE.read_text(encoding="utf-8")))
    names = sorted(used_icons())
    missing = [name for name in names if camel(name) not in paths]
    if missing:
        print("unknown icons:", ", ".join(missing), file=sys.stderr)
        return 1
    icons = {f"mdi:{name}": paths[camel(name)] for name in names}
    TARGET.write_text(
        "// Generated by dev/icons.py from @mdi/js 7.4.47 (Apache-2.0) - the icons the editor uses.\n"
        f"export const ICONS = {json.dumps(icons, indent=1)};\n",
        encoding="utf-8",
    )
    print(f"{len(icons)} icons -> {TARGET.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

export const LANGUAGES = Object.keys(STRINGS);

export function pickLanguage(saved, browser = navigator.language) {
  if (LANGUAGES.includes(saved)) return saved;
  return String(browser || "").toLowerCase().startsWith("pl") ? "pl" : "en";
}

export function translate(language, key, values = {}, fallback) {
  const text = STRINGS[language]?.[key] ?? STRINGS.en[key] ?? fallback ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (values[name] ?? `{${name}}`).toString());
}

export function keysOf(language) {
  return Object.keys(STRINGS[language]);
}
